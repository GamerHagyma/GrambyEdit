export const text: ShapeDef = {
  id: 'text',
  label: 'Text',
  params: [{ key: 'text', label: 'Text', kind: 'text', default: 'GRAMBY' }],
  fills: ['solid'],
  generate(input) {
    if (!checkInput(input)) return [];
    const { params, spacing } = input;
    // Each character takes six columns (five glyph columns and a gap), blank ones included.
    const lit: [number, number][] = [];
    [...String(params.text)].forEach((ch, index) => {
      const glyph: readonly string[] | undefined = FONT_5X7[ch];
      if (!glyph) return;
      glyph.forEach((bits, row) => {
        for (let col = 0; col < bits.length; col++) {
          if (bits[col] === '1') lit.push([(index * 6 + col) * spacing, (6 - row) * spacing]);
        }
      });
    });
    let lo = Infinity;
    let hi = -Infinity;
    for (const [x] of lit) {
      lo = Math.min(lo, x);
      hi = Math.max(hi, x);
    }
    const mid = (lo + hi) / 2; // centred on the bounding box of the lit pixels; NaN is harmless when empty
    const out: CFrame12[] = [];
    for (const [x, y] of lit) add(out, fixedFrame(x - mid, y, 0));
    return out;
  },
};
